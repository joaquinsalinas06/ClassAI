// Requires the mock web server; no backend, firmware or hardware is accessed.
// node scripts/hardware-smoke.mjs http://127.0.0.1:5188
import { chromium } from "playwright";
import assert from "node:assert/strict";
import { readFile, mkdir } from "node:fs/promises";
const base = process.argv[2] ?? "http://127.0.0.1:5188";
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto(`${base}/montajes`);
  await page.getByRole("heading", { name: "Montajes", exact: true }).waitFor();
  const draftBeforeBanks = await page.getByLabel("Nombre del montaje").inputValue();
  const collectionEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar colección JSON", exact: true }).click();
  const collectionDownload = await collectionEvent;
  const collection = JSON.parse(await readFile(await collectionDownload.path(), "utf8"));
  assert.equal(collection.format, "classai-bank-reference-v1");
  assert.equal(collection.missions.length, 12);
  for (const bank of collection.missions) {
    await page.locator(`[data-bank-id="${bank.id}"]`).click();
    const diagram = page.locator(`[data-mission-diagram="${bank.id}"]`);
    await diagram.waitFor();
    assert.equal(await diagram.locator("[data-mission-wire]").count(), bank.links.length);
    if (bank.links.some(w => w.pending)) assert.ok(await diagram.locator('path[stroke-dasharray="8 6"]').count());
  }
  assert.equal(await page.getByLabel("Nombre del montaje").inputValue(), draftBeforeBanks);
  assert.equal(await page.evaluate(() => localStorage.getItem("classai.hardware.v1")), null);
  await page.locator('[data-bank-id="nfc"]').click();
  await page.getByRole("button", { name: "Conexión siguiente", exact: true }).click();
  assert.equal(await page.locator('[data-mission-wire="0"]').getAttribute("opacity"), "1");
  const svgEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Descargar esquema SVG", exact: true }).click();
  const svgDownload = await svgEvent;
  const svg = await readFile(await svgDownload.path(), "utf8");
  assert.ok(svg.includes("PN532"));
  assert.ok(svg.includes('xmlns="http://www.w3.org/2000/svg"'));
  assert.ok(!svg.includes('opacity="0.32"'));
  await page.getByRole("button", { name: "Todas las conexiones", exact: true }).click();
  await mkdir("screenshots", { recursive: true });
  await page.locator('[data-mission-diagram="nfc"]').screenshot({ path: "screenshots/bank-nfc.png" });
  await page.locator('[data-bank-id="audio-salida"]').click();
  await page.locator('[data-mission-diagram="audio-salida"]').screenshot({ path: "screenshots/bank-audio.png" });
  await page.locator('[data-bank-id="nfc"]').click();
  assert.equal(await page.locator('[data-wire]').count(),12);
  assert.equal(await page.locator('[data-wire-color="orange"]').count(),2);
  assert.equal(await page.locator('[data-wire-color="green"]').count(),2);
  await page.getByText("Comparar placas · mapa de 30 y referencia de 38 pines", { exact: true }).click();
  assert.equal(await page.getByRole("table", { name: "Pinout de referencia 30 pines" }).getByRole("row").count(), 16);
  await page.getByRole("button", { name: "38 pines · referencia E-01 pendiente", exact: true }).click();
  assert.equal(await page.getByRole("table", { name: "Pinout de referencia 38 pines" }).getByRole("row").count(), 20);
  assert.equal(await page.locator('[data-wire]').count(), 12);
  assert.equal(await page.evaluate(() => localStorage.getItem("classai.hardware.v1")), null);
  await page.getByRole("button", { name: "30 pines · disponibles", exact: true }).click();
  await page.getByText("Comparar placas · mapa de 30 y referencia de 38 pines", { exact: true }).click();
  await page.getByRole("button", { name: "Resaltar señal OUT ↔ D4 en el montaje", exact: true }).click();
  await page.getByText(/Contacto seleccionado: ESP32 · GPIO 4/).waitFor();
  await page.getByRole("button", { name: "Resaltar unión F20 / H20 · VCC PIR", exact: true }).click();
  await page.getByText(/Contacto seleccionado: Agujero F20/).waitFor();
  await page.getByRole("button", { name: "Resaltar unión G24 / J24 · OUT PIR", exact: true }).click();
  await page.getByText(/Contacto seleccionado: Agujero G24/).waitFor();
  await page.getByRole("button", { name: "Ver reverso del PIR", exact: true }).click();
  await page.getByText("BISS0001",{exact:true}).waitFor();
  await page.getByRole("button", { name: "Ver lente del PIR", exact: true }).click();
  await page.getByRole("button", { name: "Recorrer armado", exact: true }).click();
  assert.equal(await page.locator("[data-wire]").count(), 0);
  await page.getByRole("button", { name: "Siguiente", exact: true }).click();
  assert.equal(await page.locator("[data-wire]").count(), 1);
  await page.getByRole("button", { name: "Ver todo", exact: true }).click();
  await page.getByText("Catálogo y comprobaciones del montaje", { exact: true }).click();
  await page.getByRole("button", { name: "Añadir componente", exact: true }).click();
  await page.getByLabel("Rieles cortados a mitad").check();
  await page.getByText(/dht1:VCC: alimentación sin fuente/).waitFor();
  await page.getByLabel("Rieles cortados a mitad").uncheck();
  const leg = page.getByLabel("Agujero de pata 2").last();
  await leg.selectOption("D20");
  await page.getByText(/la resistencia queda puenteada/).waitFor();
  await page.getByRole("button", { name: "Deshacer", exact: true }).click();
  assert.equal(await page.getByText(/la resistencia queda puenteada/).count(), 0);
  await page.getByLabel("Descripción de la revisión").fill("Borrador probado por navegador; sin ensayo eléctrico");
  await page.getByRole("button", { name: "Guardar revisión local", exact: true }).click();
  await page.reload();
  await page.getByText("Borrador probado por navegador; sin ensayo eléctrico", { exact: true }).waitFor();
  const before = await page.getByLabel("Nombre del montaje").inputValue();
  await page.getByLabel("Importar montaje JSON").setInputFiles({ name: "invalid.json", mimeType: "application/json", buffer: Buffer.from('{"version":99}') });
  await page.getByRole("status").filter({ hasText: "Importación rechazada" }).waitFor();
  assert.equal(await page.getByLabel("Nombre del montaje").inputValue(), before);
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar JSON", exact: true }).click();
  const download = await downloadEvent;
  const exported = JSON.parse(await readFile(await download.path(), "utf8"));
  assert.equal(exported.revisions.length, 1);
  await page.getByLabel("Nombre del montaje").fill("Otra distribución");
  await page.getByRole("button", { name: "Recuperar en borrador", exact: true }).click();
  assert.equal(await page.getByLabel("Nombre del montaje").inputValue(), before);
  assert.equal(await page.getByRole("button", { name: "Recuperar en borrador", exact: true }).count(), 1);
  await page.getByLabel("Importar montaje JSON").setInputFiles({ name: "roundtrip.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(exported)) });
  assert.equal(await page.getByLabel("Nombre del montaje").inputValue(), before);
  await mkdir("screenshots", { recursive: true });
  for (const theme of ["light", "dark"]) {
    await page.evaluate(t => localStorage.setItem("classai.theme", t), theme);
    await page.reload();
    await page.getByRole("heading", { name: "Montajes", exact: true }).waitFor();
    await page.screenshot({ path: `screenshots/hardware-${theme}-desktop.png`, fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByLabel("Elegir banco de prueba").selectOption("audio-salida");
    assert.equal(await page.locator('[data-mission-diagram="audio-salida"]').count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.screenshot({ path: `screenshots/hardware-${theme}-mobile.png`, fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
  }
  // NFC physical guide must preserve both the saved draft and in-memory edits.
  await page.goto(`${base}/montajes`);
  const storedBeforeNfc = await page.evaluate(() => localStorage.getItem("classai.hardware.v1"));
  await page.getByLabel("Nombre del montaje").fill("Cambio sin guardar antes de NFC");
  await page.locator('[data-bank-id="nfc"]').click();
  await page.getByRole("button", { name: "Abrir montaje físico NFC", exact: true }).click();
  await page.locator('[data-pn532-physical]').waitFor();
  assert.equal(await page.locator('[data-assembly-board] [data-wire]').count(), 12);
  assert.equal(await page.locator('[data-wire-number]').count(), 12);
  assert.equal(await page.getByRole("table", {name:"Seis redes NFC"}).getByRole("row").count(), 7);
  assert.equal(await page.evaluate(() => localStorage.getItem("classai.hardware.v1")), storedBeforeNfc);
  await page.getByRole("button",{name:"Deshacer",exact:true}).click();
  assert.equal(await page.getByLabel("Nombre del montaje").inputValue(), "Cambio sin guardar antes de NFC");
  await page.goto(`${base}/montajes?guia=nfc`);
  await page.locator('[data-pn532-physical]').waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem("classai.hardware.v1")), storedBeforeNfc);
  assert.equal(await page.getByRole("heading",{name:"Primer montaje · DHT11 + PIR",exact:true}).count(),0);
  for(const color of ["red","black","blue","purple","green","yellow"]) assert.equal(await page.locator(`[data-assembly-board] [data-wire-color="${color}"]`).count(),2);
  await page.getByRole("button",{name:"Ver MOSI",exact:true}).click();
  await page.getByText("Contacto seleccionado: PN532 · MOSI. Se resalta su red completa.",{exact:true}).waitFor();
  await page.getByRole("button",{name:"Recorrer armado",exact:true}).click();
  await page.getByRole("button",{name:"Siguiente",exact:true}).click();
  assert.equal(await page.locator('[data-assembly-board] [data-wire]').count(),1);
  const physicalSvgEvent=page.waitForEvent("download");
  await page.getByRole("button",{name:"Exportar dibujo SVG",exact:true}).click();
  const physicalSvg=await readFile(await (await physicalSvgEvent).path(),"utf8");
  assert.equal((physicalSvg.match(/data-wire="/g)??[]).length,12);
  assert.ok(physicalSvg.includes("data-pn532-physical"));
  assert.ok(physicalSvg.includes('xmlns="http://www.w3.org/2000/svg"'));
  assert.ok(!physicalSvg.includes('opacity=".35"'));
  const nfcJsonEvent=page.waitForEvent("download");
  await page.getByRole("button",{name:"Exportar JSON",exact:true}).click();
  const nfcJson=JSON.parse(await readFile(await (await nfcJsonEvent).path(),"utf8"));
  assert.equal(nfcJson.version,1);assert.equal(nfcJson.wires.length,12);
  assert.ok(nfcJson.parts.some(p=>p.definition==="pn532"));
  await page.getByLabel("Importar montaje JSON").setInputFiles({name:"nfc-roundtrip.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(nfcJson))});
  await page.getByRole("button",{name:"Ver todo",exact:true}).click();
  await page.getByLabel("Escala del montaje").selectOption("0.8");
  await page.locator('[data-assembly-board]').screenshot({path:"screenshots/nfc-physical.png"});
  for(const theme of ["light","dark"]) {
    await page.evaluate(t=>localStorage.setItem("classai.theme",t),theme);
    await page.reload();await page.locator('[data-pn532-physical]').waitFor();
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
    await page.screenshot({path:`screenshots/nfc-${theme}-mobile.png`,fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
  }
  // Switching back uses the same reversible editor, including preserved history.
  await page.locator('[data-bank-id="ambiente"]').click();
  await page.getByRole("button",{name:"Ver distribución física de ambiente",exact:true}).click();
  assert.equal(await page.locator('[data-pn532-physical]').count(),0);
  assert.equal(await page.locator('[data-assembly-board] [data-wire]').count(),12);
  assert.equal(await page.evaluate(() => localStorage.getItem("classai.hardware.v1")), storedBeforeNfc);
  assert.deepEqual(errors, []);
  console.log("PASS: physical NFC deep link, reversible presets, 12 M–H, full SVG/JSON, six nets, NFC mobile/light/dark; 12 banks, conditional links, SVG/collection export without draft overwrite, steps, resistor short/undo, save/reload, import rejection/roundtrip, export, snapshot recovery, light/dark, mobile, no runtime errors.");
} finally { await browser.close(); }
